#!/usr/bin/env python3
"""Convert one or more images into a Xilinx .coe file (RGB444, 12 bit per pixel).

Examples
--------
Three background pages, padded to 102,400 words (the size used by `r1.coe`):

    python tools/image2coe.py data/images/r1.png data/images/r2.png data/images/r3.png \
        -o data/coe/r1.coe --width 200 --height 150 --pad 102400

A single title screen:

    python tools/image2coe.py title.png -o data/coe/beginphoto.coe --width 200 --height 150

The script needs Pillow:  pip install -r tools/requirements.txt
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

try:
    from PIL import Image
except ImportError:  # pragma: no cover
    sys.exit("error: Pillow is required (pip install -r tools/requirements.txt)")


def load_rgb444(path: Path, width: int, height: int, background: tuple[int, int, int]) -> list[int]:
    with Image.open(path) as img:
        img = img.convert("RGBA")
        # Composite transparent pixels over a solid colour so the COE image has
        # no holes; the original backgrounds were exported with an alpha channel.
        canvas = Image.new("RGBA", img.size, (*background, 255))
        img = Image.alpha_composite(canvas, img).convert("RGB")
        img = img.resize((width, height), Image.Resampling.LANCZOS)
        raw = img.tobytes()  # R, G, B, R, G, B, ...
        return [
            ((raw[i] >> 4) << 8) | ((raw[i + 1] >> 4) << 4) | (raw[i + 2] >> 4)
            for i in range(0, len(raw), 3)
        ]


def write_coe(path: Path, words: list[int], comment: str) -> None:
    with path.open("w", encoding="ascii", newline="\n") as fh:
        fh.write(f";{len(words)}*12  {comment}\n")
        fh.write("memory_initialization_radix=16;\n")
        fh.write("memory_initialization_vector=\n")
        for i, word in enumerate(words):
            fh.write(f"{word:03X}")
            fh.write(" " if (i + 1) % 16 else "\n")
        fh.write(";\n")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("images", nargs="+", type=Path, help="input image files, in order")
    parser.add_argument("-o", "--output", required=True, type=Path, help="output .coe path")
    parser.add_argument("--width", type=int, default=200, help="output width in pixels (default 200)")
    parser.add_argument("--height", type=int, default=150, help="output height in pixels (default 150)")
    parser.add_argument("--pad", type=int, default=0,
                        help="pad with zero words up to this total (default: no padding)")
    parser.add_argument("--comment", default="", help="extra text for the first comment line")
    parser.add_argument("--background", default="000000",
                        help="RGB hex colour used for transparent pixels (default 000000)")
    args = parser.parse_args()

    if args.width <= 0 or args.height <= 0:
        parser.error("--width and --height must be positive")
    if not (len(args.background) == 6 and all(c in "0123456789abcdefABCDEF" for c in args.background)):
        parser.error("--background must be a 6-digit RGB hex value, e.g. 000000")
    background = tuple(int(args.background[i:i + 2], 16) for i in (0, 2, 4))

    words: list[int] = []
    for image in args.images:
        if not image.is_file():
            parser.error(f"no such image: {image}")
        words.extend(load_rgb444(image, args.width, args.height, background))
        print(f"  {image} -> {args.width}x{args.height}")

    generated = args.width * args.height * len(args.images)
    if len(words) != generated:
        parser.error(f"loaded {len(words)} pixels, expected {generated}")

    total = args.pad or generated
    if total < generated:
        parser.error(f"--pad {total} is smaller than the {generated} generated words")
    words.extend([0] * (total - generated))

    args.output.parent.mkdir(parents=True, exist_ok=True)
    comment = args.comment or "generated by tools/image2coe.py"
    write_coe(args.output, words, comment)
    print(f"wrote {args.output} ({len(words)} words)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
